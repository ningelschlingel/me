#!/bin/zsh
# Exports every project title image in public/projects/ at a few widths as JPEG, and writes
# src/app/shots.ts so the page can offer each screen the size it needs.
#
#   scripts/optimize-images.sh
#
# Run it again after adding or replacing an image. The originals stay untouched; empty
# placeholder files are skipped (the page keeps showing its placeholder for those).
# macOS only: uses sips. JPEG on purpose: sips can write AVIF, but some of its files decode to
# nothing in Chrome. Images with real transparency would need another format.
set -euo pipefail
cd "${0:A:h}/.."

DIR=public/projects
OUT=$DIR/sized
WIDTHS=(800 1200 1600)
JPEG_QUALITY=80
MANIFEST=src/app/shots.ts

mkdir -p $OUT
rm -f $OUT/*(N)
entries=()

for src in $DIR/*.(png|jpg|jpeg)(N); do
  [[ -s $src ]] || continue
  name=${src:t:r}
  full=$(sips -g pixelWidth $src | awk '/pixelWidth/ { print $2 }')
  made=()
  for w in $WIDTHS; do
    (( w > full )) && w=$full
    (( ${made[(Ie)$w]} )) && continue
    sips -s format jpeg -s formatOptions $JPEG_QUALITY --resampleWidth $w $src --out $OUT/$name-$w.jpg >/dev/null
    made+=($w)
  done
  entries+=("  '${src:t}': [${(j:, :)made}],")
  echo "$src → ${made[*]}"
done

{
  echo '// Generated by scripts/optimize-images.sh: do not edit.'
  echo '/** Per title image in public/projects/: the widths exported to public/projects/sized/ (JPEG). */'
  echo 'export const SHOTS: Record<string, number[]> = {'
  print -l -- $entries
  echo '};'
} > $MANIFEST

du -sh $OUT
